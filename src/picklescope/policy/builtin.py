"""Built-in policy data: the deny-list and the allow-list profiles.

The deny-list is a *backstop*, not the primary control: anything not allow-listed is
already reported. Deny entries exist to raise the severity of references that are
known to grant code execution or an equivalent primitive, and to win over an
allow-list profile that is broader than it should be. See ``docs/ALLOWLIST.md``.
"""

from __future__ import annotations

from picklescope.policy.model import Entry, Pattern, Profile


def _entries(category: str, reason: str, *patterns: str) -> tuple[Entry, ...]:
    return tuple(Entry(Pattern.parse(p), reason, category, "builtin") for p in patterns)


